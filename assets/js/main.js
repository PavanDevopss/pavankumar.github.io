function buildHeroStats(stats) {
  const wrapper = document.getElementById("hero-stats");
  if (!wrapper) {
    return;
  }

  wrapper.innerHTML = stats
    .map(
      (stat) => `
        <div>
          <dt>${stat.value}</dt>
          <dd>${stat.label}</dd>
        </div>
      `
    )
    .join("");
}

